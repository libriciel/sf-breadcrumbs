<?php

namespace Libriciel\Breadcrumbs;

use Libriciel\Breadcrumbs\Entity\BreadcrumbElement;
use PHPUnit\Framework\TestCase;

class BreadcrumbTest extends TestCase
{

    public function setUp(): void
    {
        parent::setUp(); // TODO: Change the autogenerated stub
        $this->breadcrumb = new Breadcrumb();
    }

    public function testAddToBreadcrumbs()
    {
        $this->breadcrumb->addToBreadcrumbs(new BreadcrumbElement('test'), []);
        $this->assertCount(1, $this->breadcrumb->getBreadcumbElements());
    }

    public function testGetBreadcumbElements()
    {
        $this->assertIsArray($this->breadcrumb->getBreadcumbElements());
    }

    public function testReinit()
    {
        $this->breadcrumb->addToBreadcrumbs(new BreadcrumbElement('test'), []);
        $this->breadcrumb->renit();
        $this->assertCount(0, $this->breadcrumb->getBreadcumbElements());
    }


}
